import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { parse, stringify } from "yaml";

import { loadBenchmark } from "../src/core/load.ts";
import { createPlan } from "../src/core/plan.ts";
import { runPlan } from "../src/core/run.ts";
import { planTier1, runToolPlan } from "../src/evaluation/tools.ts";
import { buildStudy, newestEvaluations } from "../tools/tier3-expert-rating/builder/build.ts";
import {
  checkStudy,
  exercisePath,
  type LoadedStudy,
  loadStudy,
  studySchema,
} from "../tools/tier3-expert-rating/builder/study.ts";

const DEMO = resolve("tools/tier3-expert-rating/demo");

let directory: string;
let studyDirectory: string;
let loaded: LoadedStudy;

/** The demo study, built from a fresh run in a temporary directory. */
beforeAll(async () => {
  directory = await mkdtemp(join(tmpdir(), "exgen-survey-"));
  const run = join(directory, "run");
  const benchmark = await loadBenchmark(join(DEMO, "benchmark.yaml"));
  await runPlan(benchmark, await createPlan(benchmark), "survey", run, { create: true });
  await runToolPlan(
    await planTier1(
      ["tier1-deterministic"],
      new Map([
        ["java-oracle", resolve("tools/tier1-deterministic/java-oracle/evaluator.fixture.yaml")],
      ]),
    ),
    { runDirectory: run, retryInfrastructure: false },
  );
  studyDirectory = join(directory, "study");
  const study = parse(await readFile(join(DEMO, "study.yaml"), "utf8"));
  for (const entry of study.exercises) {
    entry.source.run = run;
  }
  study.build.oracle = resolve("tools/tier1-deterministic/java-oracle/config.fixture.yaml");
  await Bun.write(join(studyDirectory, "study.yaml"), stringify(study));
  await buildStudy(studyDirectory);
  loaded = await loadStudy(studyDirectory);
}, 120_000);

afterAll(async () => {
  await rm(directory, { recursive: true, force: true });
});

describe("building a study", () => {
  test("freezes every exercise under a random ID and keeps the IDs on a rebuild", async () => {
    expect(loaded.manifest.exercises.map((entry) => entry.code)).toEqual(["E1", "M1", "L1"]);
    expect(new Set(loaded.manifest.exercises.map((entry) => entry.id)).size).toBe(3);
    const rebuilt = await buildStudy(studyDirectory);
    expect(rebuilt.exercises.map((entry) => entry.id)).toEqual(
      loaded.manifest.exercises.map((entry) => entry.id),
    );
  });

  test("reads only each evaluator's newest evaluation of a candidate", () => {
    const response = (evaluator: string, attempt: string, finished: string) => ({
      evaluator: { id: evaluator },
      candidate: { attempt_id: attempt },
      finished_at: finished,
    });
    const older = response("promise-traceability", "a", "2026-10-21T10:00:00Z");
    const newer = response("promise-traceability", "a", "2026-10-29T17:00:00+01:00");
    const oracle = response("java-oracle", "a", "2026-10-20T10:00:00Z");
    const other = response("promise-traceability", "b", "2026-10-30T10:00:00Z");
    expect(newestEvaluations([newer, oracle, older, other], "a")).toEqual([newer, oracle]);
  });

  test("removes the file of an exercise the study no longer lists", async () => {
    const dropped = exercisePath(studyDirectory, "ZZ9Z");
    await writeFile(dropped, "{}\n");
    await buildStudy(studyDirectory);
    expect(await Bun.file(dropped).exists()).toBe(false);
    expect(await Bun.file(join(studyDirectory, "exercises", "BLINDING.md")).exists()).toBe(true);
  });

  test("blinds the generator's name and logs every replacement for review", async () => {
    const e1 = loaded.manifest.exercises.find((entry) => entry.code === "E1");
    expect(e1?.blinding_replacements).toBe(1);
    expect(JSON.stringify(loaded.exercises.get("E1"))).toContain("// Generated by [removed].");
    const log = await readFile(join(studyDirectory, "exercises", "BLINDING.md"), "utf8");
    expect(log).toContain(
      `| E1 | ${e1?.id} | template/src/de/tum/cit/aet/stepstatistics/StepStatistics.java.content | 1 | \`demo-generator\` |`,
    );
  });

  test("puts only what raters may see into an exercise", () => {
    const exercise = loaded.exercises.get("L1");
    expect(exercise?.statement).not.toContain("testid");
    expect(exercise?.statement).toContain("[task][");
    expect(exercise?.tests.flatMap((group) => group.tests).length).toBe(exercise?.facts.tests);
    expect(JSON.stringify(exercise)).not.toContain("demo-generator");
  });

  test("reports supported findings and explicitly marks unavailable probes", () => {
    const findings = loaded.exercises.get("E1")?.findings;
    expect(findings?.items.map((finding) => finding.title)).toContain(
      "Tests compare floating-point values without a tolerance",
    );
    const labels = findings?.metrics.map((metric) => metric.label) ?? [];
    expect(labels).toContain("Code-change probes");
    expect(labels).not.toContain("Build and gates");
  });

  test("refuses to change an exercise that was built before", async () => {
    const studyFile = join(studyDirectory, "study.yaml");
    const original = await readFile(studyFile, "utf8");
    const study = parse(original);
    study.build.blinding = ["Steps"];
    await writeFile(studyFile, stringify(study));
    try {
      await expect(buildStudy(studyDirectory)).rejects.toThrow(
        "was built before with different content",
      );
    } finally {
      await writeFile(studyFile, original);
    }
  });

  test("refuses an exercise file edited after it was built", async () => {
    const file = exercisePath(studyDirectory, loaded.idOf.get("M1") ?? "");
    const original = await readFile(file, "utf8");
    await writeFile(file, original.replace("Library", "Libary"));
    try {
      await expect(loadStudy(studyDirectory)).rejects.toThrow("changed after it was built");
    } finally {
      await writeFile(file, original);
    }
  });

  test("rebuilds over a build another version wrote, keeping its IDs, and refuses to serve it", async () => {
    const path = join(studyDirectory, "exercises", "manifest.json");
    const manifest = JSON.parse(await readFile(path, "utf8")) as {
      exercises: Array<Record<string, unknown>>;
    };
    // An earlier format had a field this version no longer knows.
    for (const entry of manifest.exercises) entry.diagrams = "none";
    await writeFile(path, JSON.stringify(manifest));
    await expect(loadStudy(studyDirectory)).rejects.toThrow(
      "built by another version of exgen-bench; rebuild them with: exgen survey build --rebuild",
    );
    const rebuilt = await buildStudy(studyDirectory);
    expect(rebuilt.exercises.map((entry) => entry.id)).toEqual(
      loaded.manifest.exercises.map((entry) => entry.id),
    );
    expect((await loadStudy(studyDirectory)).manifest).toEqual(loaded.manifest);
  });

  test("accepts the demo plan and warns that its oracle replays recordings", () => {
    const report = checkStudy(loaded);
    expect(report.problems).toEqual([]);
    expect(report.warnings).toContain(
      "the test overview comes from recorded fixture builds, not from building the exercises",
    );
  });

  test("checks a study before it is built, and refuses the wrong instrument version", () => {
    const { study, instrument } = loaded;
    expect(checkStudy({ study, instrument }).warnings).toContain(
      "the exercises are not built yet; run exgen survey build",
    );
    expect(
      checkStudy({ study: { ...study, instrument_version: "0" }, instrument }).problems,
    ).toEqual([
      `the study was designed for instrument version 0, but this exgen-bench has version ${instrument.version}`,
    ]);
  });

  test("refuses a study that still defines a calibration exercise", async () => {
    // Instrument version 3 has no practice exercise; a study written for version 2 must not pass
    // silently with its calibration ignored.
    const study = parse(await readFile(join(DEMO, "study.yaml"), "utf8"));
    expect(studySchema.safeParse(study).success).toBe(true);
    const calibration = { code: "CAL", phase: "early", source: study.exercises[0].source };
    const result = studySchema.safeParse({ ...study, calibration });
    expect(result.error?.issues.map((issue) => issue.message)).toEqual([
      'Unrecognized key: "calibration"',
    ]);
  });

  test("lets a pilot without main raters run, and refuses built exercises it no longer plans", () => {
    const pilot = {
      ...loaded,
      study: {
        ...loaded.study,
        exercises: loaded.study.exercises.filter((entry) => entry.code !== "M1"),
        raters: loaded.study.raters.filter((rater) => rater.role !== "main"),
      },
    };
    const report = checkStudy(pilot);
    expect(report.warnings).toContain(
      "the study has no main raters, so none of its answers are analysed",
    );
    expect(report.problems).toEqual(["built exercises are no longer in study.yaml: M1"]);
  });
});
